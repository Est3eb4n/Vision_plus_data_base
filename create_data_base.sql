CREATE DATABASE IF NOT EXISTS sistema_alertas;
 USE sistema_alertas;

CREATE TABLE LOCALIDAD (
 ID_Localidad INT AUTO_INCREMENT,
 Nombre_Localidad VARCHAR(100) NOT NULL,
 PRIMARY KEY (ID_Localidad)
 );

CREATE TABLE ESTADO_ALERTA (
 ID_Estado INT AUTO_INCREMENT,
 Nombre_Estado VARCHAR(50) NOT NULL,
 PRIMARY KEY (ID_Estado)
 );

CREATE TABLE TIPO_DOCUMENTO (
 ID_Tipo_Doc INT AUTO_INCREMENT,
 Nombre_Doc VARCHAR(50) NOT NULL,
 PRIMARY KEY (ID_Tipo_Doc)
 );

CREATE TABLE TIPO_RH (
 ID_RH INT AUTO_INCREMENT,
 Grupo_RH VARCHAR(10) NOT NULL,
 PRIMARY KEY (ID_RH)
 );

CREATE TABLE EPS (
 ID_EPS INT AUTO_INCREMENT,
 Nombre_EPS VARCHAR(100) NOT NULL,
 Direccion_EPS VARCHAR(150),
 Telefono VARCHAR(20),
 Email VARCHAR(100),
 PRIMARY KEY (ID_EPS)
 );

CREATE TABLE CONDICION_MEDICA (
 ID_Condicion INT AUTO_INCREMENT,
 Tipo_Condicion VARCHAR(100) NOT NULL,
 Descripcion TEXT,
 PRIMARY KEY (ID_Condicion)
 );

CREATE TABLE GRADO_DISCAPACIDAD (
 ID_Discapacidad INT AUTO_INCREMENT,
 Discapacidad VARCHAR(100) NOT NULL,
 PRIMARY KEY (ID_Discapacidad)
 );

CREATE TABLE BARRIO (
 ID_Barrio INT AUTO_INCREMENT,
 ID_Localidad INT NOT NULL,
 Nombre_Barrio VARCHAR(100) NOT NULL,
 PRIMARY KEY (ID_Barrio),
 CONSTRAINT FK_Barrio_Localidad 
 FOREIGN KEY (ID_Localidad) REFERENCES LOCALIDAD(ID_Localidad)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE TIPO_ALERTA (
 ID_Tipo_Alerta INT AUTO_INCREMENT,
 ID_Estado INT NOT NULL,
 Nombre_Alerta VARCHAR(100) NOT NULL,
 PRIMARY KEY (ID_Tipo_Alerta),
 CONSTRAINT FK_TipoAlerta_Estado 
 FOREIGN KEY (ID_Estado) REFERENCES ESTADO_ALERTA(ID_Estado)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE USUARIO (
 ID_Usuario INT AUTO_INCREMENT,
 ID_Tipo_Doc INT NOT NULL,
 Num_Doc VARCHAR(20) NOT NULL UNIQUE,
 Nombre VARCHAR(100) NOT NULL,
 Fecha_Nacimiento DATE NOT NULL,
 ID_RH INT NOT NULL,
 ID_EPS INT NOT NULL,
 PRIMARY KEY (ID_Usuario),
 CONSTRAINT FK_Usuario_TipoDoc 
 FOREIGN KEY (ID_Tipo_Doc) REFERENCES TIPO_DOCUMENTO(ID_Tipo_Doc)
 ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT FK_Usuario_TipoRH 
 FOREIGN KEY (ID_RH) REFERENCES TIPO_RH(ID_RH)
 ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT FK_Usuario_EPS 
 FOREIGN KEY (ID_EPS) REFERENCES EPS(ID_EPS)
 ON DELETE RESTRICT ON UPDATE CASCADE
 );

CREATE TABLE UBICACION (
 ID_Ubicacion INT AUTO_INCREMENT,
 ID_Barrio INT NOT NULL,
 Direccion VARCHAR(150) NOT NULL,
 Latitud DECIMAL(10, 8) NOT NULL,
 Longitud DECIMAL(11, 8) NOT NULL,
 PRIMARY KEY (ID_Ubicacion),
 CONSTRAINT FK_Ubicacion_Barrio 
 FOREIGN KEY (ID_Barrio) REFERENCES BARRIO(ID_Barrio)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE CONTACTO_EMERGENCIA (
 ID_Contacto INT AUTO_INCREMENT,
 ID_Usuario INT NOT NULL,
 Nombre VARCHAR(100) NOT NULL,
 Num_Tel VARCHAR(20) NOT NULL,
 Direccion VARCHAR(150),
 PRIMARY KEY (ID_Contacto),
 CONSTRAINT FK_ContactoEmergencia_Usuario 
 FOREIGN KEY (ID_Usuario) REFERENCES USUARIO(ID_Usuario)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE USUARIO_CONDICION (
 ID_Usuario INT NOT NULL,
 ID_Condicion INT NOT NULL,
 PRIMARY KEY (ID_Usuario, ID_Condicion),
 CONSTRAINT FK_UsuarioCondicion_Usuario 
 FOREIGN KEY (ID_Usuario) REFERENCES USUARIO(ID_Usuario)
 ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT FK_UsuarioCondicion_Condicion 
 FOREIGN KEY (ID_Condicion) REFERENCES CONDICION_MEDICA(ID_Condicion)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE USUARIO_DISCAPACIDAD (
 ID_Usuario INT NOT NULL,
 ID_Discapacidad INT NOT NULL,
 PRIMARY KEY (ID_Usuario, ID_Discapacidad),
 CONSTRAINT FK_UsuarioDiscapacidad_Usuario 
 FOREIGN KEY (ID_Usuario) REFERENCES USUARIO(ID_Usuario)
 ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT FK_UsuarioDiscapacidad_Discapacidad 
 FOREIGN KEY (ID_Discapacidad) REFERENCES GRADO_DISCAPACIDAD(ID_Discapacidad)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE LUGARES_FRECUENTES (
 ID_Lugar_Frec INT AUTO_INCREMENT,
 ID_Usuario INT NOT NULL,
 ID_Ubicacion INT NOT NULL,
 Alias_Lugar VARCHAR(50) NOT NULL,
 PRIMARY KEY (ID_Lugar_Frec),
 CONSTRAINT FK_LugaresFrecuentes_Usuario 
 FOREIGN KEY (ID_Usuario) REFERENCES USUARIO(ID_Usuario)
 ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT FK_LugaresFrecuentes_Ubicacion 
 FOREIGN KEY (ID_Ubicacion) REFERENCES UBICACION(ID_Ubicacion)
 ON DELETE CASCADE ON UPDATE CASCADE
 );

CREATE TABLE LISTA_ALERTAS (
 ID_Alerta INT AUTO_INCREMENT,
 ID_Usuario INT NOT NULL,
 ID_Tipo_Alerta INT NOT NULL,
 ID_Ubicacion INT NOT NULL,
 Fecha_Hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 Indicaciones TEXT,
 PRIMARY KEY (ID_Alerta),
 CONSTRAINT FK_ListaAlertas_Usuario 
 FOREIGN KEY (ID_Usuario) REFERENCES USUARIO(ID_Usuario)
 ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT FK_ListaAlertas_TipoAlerta 
 FOREIGN KEY (ID_Tipo_Alerta) REFERENCES TIPO_ALERTA(ID_Tipo_Alerta)
 ON DELETE RESTRICT ON UPDATE CASCADE,
 CONSTRAINT FK_ListaAlertas_Ubicacion 
 FOREIGN KEY (ID_Ubicacion) REFERENCES UBICACION(ID_Ubicacion)
 ON DELETE RESTRICT ON UPDATE CASCADE
 );